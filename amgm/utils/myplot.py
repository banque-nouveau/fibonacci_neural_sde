def regression_time_performance(y_true, y_hat, wdir, mean_MAE=None, std_MAE=None, model="daily_378_63_US_Stocks"):
    """
    Plots the regression performance with two subplots:
    1. Mean Absolute Error (MAE) per label
    2. Scatter plot of predictions vs true labels with mean and std error bars for each label.
    
    Parameters:
    y_true (np.ndarray): True labels.
    y_hat (np.ndarray): Predicted labels.
    mean_MAE (array-like): Mean MAE for each label.
    std_MAE (array-like): Standard deviation of MAE for each label.
    wdir (Path): Directory to save the plots.
    model (str): Model name for the plot title.
    """
    w_tst = int(model.split("_")[2])  # Extract window_size_test from model name, e.g., "daily_378_63_US_Stocks" -> "63"
    unique_classes, counts = np.unique(y_true, return_counts=True)

    if mean_MAE is None or std_MAE is None:
        # Compute mean absolute error for each label
        errors = y_true - y_hat
        mean_MAE = [np.abs(errors[y_true == label]).mean() for label in unique_classes]
    
    mean_y_hat_per_label = [y_hat[y_true == label].mean() for label in unique_classes]
    std_y_hat_per_label = [y_hat[y_true == label].std() for label in unique_classes]

    
    fig, axes = plt.subplots(1, 2, figsize=(16, 6))
    # Set a common title for the entire figure
    fig.suptitle("Regression time Performance, labels: days counting from the end of the lookforward window", fontsize=16, fontweight='bold')
    # Subplot 1: MAE per label
    if mean_MAE is not None and std_MAE is not None:
        axes[0].errorbar(unique_classes, mean_MAE, yerr=std_MAE, fmt='-o', ecolor='r', capsize=5, label='MAE ± Std')
    else:
        axes[0].plot(unique_classes, mean_MAE, '-o', label= 'MAE')
    axes[0].set_xlim(-w_tst-1, w_tst+1)
    axes[0].set_xlabel('Label')
    axes[0].set_ylabel('Mean Absolute Error (days)')
    axes[0].set_title('MAE per Label')
    axes[0].legend()
    axes[0].grid(True)

    # Subplot 2: prediction vs label scatter
    axes[1].scatter(y_true, y_hat, alpha=0.2, s=5, label='Predictions')
    axes[1].plot([-w_tst, w_tst], [-w_tst, w_tst], 'r--', label='Ideal: y_hat = y_true')
    axes[1].errorbar(unique_classes, mean_y_hat_per_label, yerr=std_y_hat_per_label, fmt='o', color='green', label='Mean ± Std of Predictions')    
    axes[1].set_xlim(-w_tst-1, w_tst+1)
    axes[1].set_xlabel('Label')
    axes[1].set_ylabel('Prediction')
    axes[1].set_title('Validation Predictions vs Labels')
    axes[1].legend()
    axes[1].grid(True)

    plt.tight_layout()
    if wdir is not None:
        plt.savefig(wdir / f"regression_time_{model}.png", dpi=150, bbox_inches='tight')
        plt.close()
    else:
        return fig
    

