def synthetic_NSDE_path(sample, synthetic_path, original_price, wdir, output_plot, font_size=12):  
    """
    Plots the synthetic path generated by the Neural SDE model along with the historical price window and Fibonacci levels.
    """
    
    hist = sample.price_window.detach().cpu().numpy()
    price_min = sample.sample_min.detach().cpu().numpy()
    price_range = sample.sample_range.detach().cpu().numpy()
    fib_levels = sample.fib_levels.detach().cpu().numpy()
    test_date = sample.test_dates
    issue_id = sample.issue_ids
    sample_output_plot = output_plot.with_name(f"{output_plot.stem}_{issue_id}_{test_date}.png")
    
    hist = hist * price_range + price_min  # Denormalize the historical window
    fib_levels = fib_levels * price_range + price_min  # Denormalize the Fibonacci levels
    
    hist_idx = np.arange(len(hist))
    fut_idx = np.arange(len(hist) - 1, len(hist) - 1 + len(synthetic_path))
    
    # One-column paper friendly size (~3.35in wide) with a less rectangular aspect.
    scale_factor = 2
    fig, ax = plt.subplots(figsize=(3.35 * scale_factor, 2.6 * scale_factor))
    ax.plot(hist_idx, hist, label="seed window", color="black", linewidth=2)
    ax.plot(fut_idx, synthetic_path, label="synthetic rollout", color="tab:blue", linewidth=2)
    ax.scatter([fut_idx[0]], [synthetic_path[0]], color="tab:red", zorder=5, label="SDE start")
    original_price = np.asarray(original_price)
    original_price_len = min(len(fut_idx), len(original_price))
    if original_price_len > 0:
        ax.plot(
            fut_idx[:original_price_len],
            original_price,
            label="original price",
            color="tab:green",
            linewidth=2,
        )
    x_min, x_max = 0, 352
    ax.set_xlim(x_min, x_max)
    ### Customize x-ticks to include the test date and avoid overlap
    current_ticks = ax.get_xticks()
    positive_ticks = current_ticks[current_ticks >= 0]
    if len(positive_ticks) > 1:
        tick_spacing = float(np.min(np.diff(positive_ticks)))
        min_distance_to_test_date = tick_spacing * 0.5
        filtered_ticks = positive_ticks[np.abs(positive_ticks - fut_idx[0]) > min_distance_to_test_date]
    else:
        filtered_ticks = positive_ticks
    custom_ticks = np.unique(np.append(filtered_ticks, fut_idx[0]))
    custom_ticks = custom_ticks[(custom_ticks >= x_min) & (custom_ticks <= x_max)]
    custom_labels = [str(test_date) if np.isclose(tick, fut_idx[0]) else f"{int(round(tick))}" for tick in custom_ticks]
    ax.set_xticks(custom_ticks)
    ax.set_xticklabels(custom_labels)
    ax.set_xlim(x_min, x_max)
    for tick, label in zip(custom_ticks, ax.get_xticklabels()):
        if np.isclose(tick, fut_idx[0]):
            label.set_rotation(45)
            label.set_horizontalalignment("right")
            label.set_color("red")
    ###        
    plot_fib_levels(fib_levels, ax)
    ax.set_xlabel("Step", fontsize=font_size)
    ax.set_ylabel("Price (USD)", fontsize=font_size)
    ax.set_title(f"Neural SDE synthetic rollout for {len(synthetic_path)-1} steps", fontsize=font_size)
    ax.legend(loc="best", fontsize=font_size)
    ax.tick_params(axis="both", labelsize=font_size)
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(sample_output_plot, dpi=300)
    plt.close(fig)
    
