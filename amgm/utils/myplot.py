def plot_entropy_calibration_curve(entropy, prediction_difficulty_scores, issue_id, wdir, lookback=252, time_bar="daily"):
    """
    Plot binned calibration curve showing average entropy per difficulty bucket.
    
    This reveals whether entropy is well-calibrated with prediction difficulty:
    - Well-calibrated: entropy increases monotonically with difficulty
    - Poorly-calibrated: entropy doesn't correlate with difficulty
    
    Parameters:
    -----------
    entropy : array-like, shape (N,)
        Shannon entropy per prediction
    prediction_difficulty_scores : array-like, shape (N,)
        Prediction difficulty scores in [0, 1]
    issue_id : str
        Security identifier for plot title
    wdir : Path
        Working directory to save plot
    lookback : int
        Lookback period for plot naming
    time_bar : str
        Time bar type for plot naming
    """
    # Early return if no difficulty scores provided
    if prediction_difficulty_scores is None:
        print("Warning: prediction_difficulty_scores is None. Skipping entropy calibration curve.")
        return
    
    # Convert to numpy if needed
    if hasattr(entropy, 'cpu'):
        entropy = entropy.cpu().numpy()
    if hasattr(prediction_difficulty_scores, 'cpu'):
        prediction_difficulty_scores = prediction_difficulty_scores.cpu().numpy()
    
    n_bins = 10
    bin_edges = np.linspace(0, 1, n_bins + 1)
    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2
    
    # Compute average entropy per difficulty bin
    avg_entropy_per_bin = []
    counts_per_bin = []
    
    for i in range(n_bins):
        mask = (prediction_difficulty_scores >= bin_edges[i]) & (prediction_difficulty_scores < bin_edges[i+1])
        if mask.sum() > 0:
            avg_entropy_per_bin.append(entropy[mask].mean())
            counts_per_bin.append(mask.sum())
        else:
            avg_entropy_per_bin.append(np.nan)
            counts_per_bin.append(0)
    
    avg_entropy_per_bin = np.array(avg_entropy_per_bin)
    counts_per_bin = np.array(counts_per_bin)
    
    # Create calibration curve plot
    fig, ax = plt.subplots(figsize=(10, 6))
    
    # Plot entropy vs difficulty
    ax.plot(bin_centers, avg_entropy_per_bin, 'o-', linewidth=2.5, markersize=8, 
            color='#1f77b4', label='Average Entropy')
    
    # Add count annotations
    for i, (center, entropy_val, count) in enumerate(zip(bin_centers, avg_entropy_per_bin, counts_per_bin)):
        if count > 0:
            ax.annotate(f'n={int(count)}', xy=(center, entropy_val), 
                       xytext=(0, 8), textcoords='offset points', 
                       ha='center', fontsize=8, color='gray')
    
    ax.set_xlabel('Prediction Difficulty Score', fontsize=12, fontweight='bold')
    ax.set_ylabel('Average Shannon Entropy', fontsize=12, fontweight='bold')
    ax.set_title(f'Entropy Calibration Curve - {issue_id} (lookback={lookback})', 
                fontsize=13, fontweight='bold')
    ax.grid(True, alpha=0.3)
    ax.legend(fontsize=11)
    ax.set_xlim(-0.05, 1.05)
    ax.set_ylim(bottom=0)
    
    plt.tight_layout()
    
    # Save plot
    plot_filename = wdir / f"entropy_calibration_{issue_id}_{time_bar}_{lookback}.png"
    plt.savefig(plot_filename, dpi=150, bbox_inches='tight')
    plt.close()

