def plot_entropy_difficulty_bins(entropy, prediction_difficulty_scores, issue_id, wdir, lookback, time_bar, num_classes=3, y_hat=None, y_true=None):
    """
    Create a 2D binned plot showing distribution of samples across entropy-difficulty categories.
    
    Parameters:
    -----------
    entropy : array-like, shape (N,)
        Shannon entropy for each prediction
    prediction_difficulty_scores : array-like, shape (N,)
        Prediction difficulty scores for each prediction
    issue_id : str/int
        Stock identifier
    wdir : Path
        Working directory to save the plot
    lookback : int
        Lookback window size (for filename)
    time_bar : str
        Time bar specification
    num_classes : int, optional
        Number of classes (for max entropy calculation)
    y_hat : array-like, optional
        Predicted labels (for accuracy per bin)
    y_true : array-like, optional
        True labels (for accuracy per bin)
    """
    # Convert to numpy if needed
    if hasattr(entropy, 'cpu'):
        entropy = entropy.cpu().numpy()
    if hasattr(prediction_difficulty_scores, 'cpu'):
        prediction_difficulty_scores = prediction_difficulty_scores.cpu().numpy()
    if y_hat is not None and hasattr(y_hat, 'cpu'):
        y_hat = y_hat.cpu().numpy()
    if y_true is not None and hasattr(y_true, 'cpu'):
        y_true = y_true.cpu().numpy()
    
    # Normalize entropy to [0, 1] range for easier binning
    max_entropy = np.log(num_classes)
    entropy_norm = entropy / max_entropy
    
    # Define bin edges (Low: 0-0.33, Medium: 0.33-0.67, High: 0.67-1.0)
    bin_edges = [0, 0.33, 0.67, 1.0]
    bin_labels = ['Low', 'Med', 'High']
    
    # Create 2D histogram
    entropy_bins = np.digitize(entropy_norm, bin_edges[:-1]) - 1
    difficulty_bins = np.digitize(prediction_difficulty_scores, bin_edges[:-1]) - 1
    
    # Clip to valid range (0, 1, 2)
    entropy_bins = np.clip(entropy_bins, 0, 2)
    difficulty_bins = np.clip(difficulty_bins, 0, 2)
    
    # Count samples in each bin
    counts = np.zeros((3, 3))
    accuracies = np.zeros((3, 3))
    
    for i in range(3):  # entropy bins
        for j in range(3):  # difficulty bins
            mask = (entropy_bins == i) & (difficulty_bins == j)
            counts[i, j] = mask.sum()
            
            # Calculate accuracy for this bin if labels provided
            if y_hat is not None and y_true is not None and mask.sum() > 0:
                accuracies[i, j] = (y_hat[mask] == y_true[mask]).mean() * 100
    
