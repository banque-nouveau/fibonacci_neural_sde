def highlight_ci(x_index, y, window_size_train, window_size_test, time_bar, color, y_hat_reg_time=None, y_hat_reg_residual=None):
    """
    Highlights the 95% confidence interval of a linear regression model on a plot.
    Additionally highlights the regression-predicted border region if y_hat_reg_time is provided.
    
    Parameters:
    -----------
    x_index : array-like
        X-axis indices for plotting
    y : array-like
        Y-axis values (price data)
    window_size_train : int
        Size of training window
    window_size_test : int
        Size of test window
    time_bar : str
        Time frequency ('daily', 'weekly', or 'monthly')
    color : str
        Color for main CI highlight
    y_hat_reg_time : float, optional
        Regression prediction for days from the end of the window.
        Positive values indicate upper boundary, negative for lower boundary.
    y_hat_reg_residual : float, shape: (1,10), optional
        Percentage deviation above/below the 95% CI borders (in percentage form, e.g., 5 for 5%).
        Positive values plot above upper border, negative below lower border. Zero means inside the CI.
    Example usage:
        plt.figure(figsize=(10, 6))
        plt.plot(x_252, x_val_252[row, :], linewidth=2, label='252-day Model', color='blue')
        highlight_ci(x_252, y, color='blue', y_hat_reg_time=y_hat_reg_time)
        plt.grid()
    """
    # Fit linear model
    # Assuming y is a PyTorch tensor of shape [252, 1]
    y = y.squeeze().numpy()  # Convert to NumPy array and remove extra dimension
    x = np.arange(len(y))
    y_train = y[:window_size_train]
    x_train = x[:window_size_train]
    # Resample to the time bar frequency
    d = dict(daily=1, weekly=5, monthly=21)[time_bar]
    y_downsampled = y_train[::d]
    x_downsampled = x_train[::d]
    slope, intercept = common.fast_linreg_numba(x_downsampled, y_downsampled)
    y_pred = intercept + slope * x_train
    residuals = y_train - y_pred
    ci = 1.96 * np.std(residuals)
    
    y_linear = intercept + slope * x_index
    y_lower_border = y_linear - ci
    y_upper_border = y_linear + ci
  
    plt.plot(x_index, y_linear, color=color, linestyle='-', linewidth=2, label='Linear Fit')
    # Plot confidence interval
    plt.fill_between(x_index, y_lower_border, y_upper_border, color=color, alpha=0.2, label='95% CI')
    
    # Plot ensemble model predictions as markers if y_hat_reg_time is provided
    if y_hat_reg_time is not None:
        # Convert to numpy if it's a tensor
        y_hat_reg_time = y_hat_reg_time.cpu().numpy()
        y_hat_reg_time = np.asarray(y_hat_reg_time).flatten()  # Flatten to 1D array
        
        x_end = x_index[-1]  # Last index (end of window)
        
        # Plot a marker for each ensemble prediction
        for i, y_hat_reg in enumerate(y_hat_reg_time):
            y_hat_reg = float(y_hat_reg)
            
            # Calculate x-position: x_end - |days_from_end|
            x_marker = x_end - abs(y_hat_reg)
            
            if y_hat_reg >= 1:
                # Positive: marker on UPPER boundary (y_linear + ci)
                y_marker = np.interp(x_marker, x_index, y_upper_border)
                plt.plot(x_marker, y_marker, marker='o', linestyle='none', markersize=6, color='green', 
                        markeredgecolor='darkgreen', markeredgewidth=1, zorder=11, 
                        label='Touch Prediction' if i == 0 else None)
            elif y_hat_reg <= -1:
                # Negative: marker on LOWER boundary (y_linear - ci)
                y_marker = np.interp(x_marker, x_index, y_lower_border)
                plt.plot(x_marker, y_marker, marker='o', linestyle='none', markersize=6, color='red', 
                        markeredgecolor='darkred', markeredgewidth=1, zorder=11,
                        label='Touch Prediction' if i == 0 else None)
            else:
                # Values between -1 and +1: interpolate y_marker between lower and upper CI at x_end
                x_marker = x_end  # Marker at the end of the window
                y_marker = np.interp(y_hat_reg, [-1, 1], [y_lower_border[-1], y_upper_border[-1]])
                plt.plot(x_marker, y_marker, marker='o', linestyle='none', markersize=6, color='blue', 
                        markeredgecolor='darkblue', markeredgewidth=1, zorder=11,
                        label='Touch Prediction' if i == 0 else None)
              
    # Plot residual borders if y_hat_reg_residual is provided
    if y_hat_reg_residual is not None:
        # Convert to numpy if it's a tensor
        # Flatten to 1D array
        y_hat_reg_residual = np.asarray(y_hat_reg_residual).flatten()
        
        # Get indices for last window_size_test days
        x_residual = x_index[-window_size_test-1:]
        y_lower_border_test = y_lower_border[-window_size_test-1:]
        y_upper_border_test = y_upper_border[-window_size_test-1:]
        
        # Filter out zero values for statistics
        non_zero_residuals = y_hat_reg_residual[y_hat_reg_residual != 0]
        
        if len(non_zero_residuals) > 0:
            # Calculate statistics
            residual_mean = np.mean(non_zero_residuals)
            residual_std = np.std(non_zero_residuals)
            
            # Calculate mean+std and mean-std
            mean_plus_std = float(residual_mean + residual_std)
            mean_minus_std = float(residual_mean - residual_std)
            residual_mean = float(residual_mean)
            
            print(f"Residual Mean: {residual_mean:.2f}%, Residual Std: {residual_std:.2f}%, Mean+Std: {mean_plus_std:.2f}%, Mean-Std: {mean_minus_std:.2f}%")
            print(f"y_hat_reg_residual: {y_hat_reg_residual}")
            # Calculate borders for mean
            if residual_mean >= 0:
                y_residual_mean = y_upper_border_test * (1 + residual_mean / 100)
                color_mean = 'green'
            else:
                y_residual_mean = y_lower_border_test * (1 + residual_mean / 100)
                color_mean = 'red'
            
            # Plot mean line
            plt.plot(x_residual, y_residual_mean, color=color_mean, linestyle='-', linewidth=2, alpha=0.8,
                    label='Residual Prediction Mean')
            
            # Calculate and highlight borders for mean+std
            if mean_plus_std > 0 and mean_minus_std > 0:
                y_residual_upper = y_upper_border_test * (1 + mean_plus_std / 100)
                y_residual_lower = y_upper_border_test * (1 + mean_minus_std / 100)
                plt.fill_between(x_residual, y_residual_lower, y_residual_upper, 
                                color='green', alpha=0.2, label='Uncertainty Range ($\pm$std)')
            elif mean_plus_std >= 0 and mean_minus_std <= 0:
                y_residual_upper = y_upper_border_test * (1 + mean_plus_std / 100)
                y_residual_lower = y_lower_border_test * (1 + mean_minus_std / 100)
                plt.fill_between(x_residual, y_upper_border_test, y_residual_upper, 
                                color='green', alpha=0.2, label='Uncertainty Range ($+$std)')
                plt.fill_between(x_residual, y_residual_lower, y_lower_border_test,
                                color='red', alpha=0.2, label='Uncertainty Range ($-$std)')
            elif mean_plus_std < 0 and mean_minus_std < 0:
                y_residual_upper = y_lower_border_test * (1 + mean_plus_std / 100)
                y_residual_lower = y_lower_border_test * (1 + mean_minus_std / 100)
                plt.fill_between(x_residual, y_residual_lower, y_residual_upper, 
                                color='red', alpha=0.2, label='Uncertainty Range ($\pm$std)')
        
        # Annotate the mean value at x_index[-t_ind]
        t_ind = 1
        x_text = x_index[-t_ind]
        
        # Calculate y position for mean
        if residual_mean >= 0:
            y_border_mean = y_upper_border_test * (1 + residual_mean / 100)
            y_text_mean = y_border_mean[-t_ind]
            plt.text(x_text, y_text_mean, f"{residual_mean:.1f}%", color='green', va='top', ha='left', fontsize=9)
        else:
            y_border_mean = y_lower_border_test * (1 + residual_mean / 100)
            y_text_mean = y_border_mean[-t_ind]
            plt.text(x_text, y_text_mean, f"{residual_mean:.1f}%", color='red', va='top', ha='left', fontsize=9)
    
    # Annotate the upper and lower CI at the last x value
    x_last = x_index[-1]
    y_lower = round(y_linear[-1] - ci, 1)
    y_upper = round(y_linear[-1] + ci, 1)
    plt.text(x_last, y_lower, f"{y_lower}", color='orange', va='bottom', ha='left', fontsize=9)
    plt.text(x_last, y_upper, f"{y_upper}", color='orange', va='top', ha='left', fontsize=9)
    
    # Return minimum of y_lower_border for conditional y-limit setting
    return np.min(y_residual_lower)
    
    
