def histogram_of_slope(slope_errors, slope_total, error_type, wdir, num_bins, lookback):
    """
    Plots a histogram of slope of errors and total slopes.
    """
    x_value = 1/lookback  # Assuming lookback is in days, e.g., 252 for a year
    
    plt.figure(figsize=(10, 6))

    # Compute bin edges
    bin_edges = np.linspace(-0.006, 0.006, num_bins+1)

    # Compute histograms
    error_counts, _ = np.histogram(slope_errors, bins=bin_edges)
    total_counts, _ = np.histogram(slope_total, bins=bin_edges)

    # Avoid division by zero
    ratio = np.divide(error_counts, total_counts, out=np.zeros_like(error_counts, dtype=float), where=total_counts!=0)

    # Plot histograms (stacked bars)
    plt.hist([slope_errors, slope_total],
             bins=bin_edges,
             label=[error_type, 'Total'],
             color=['salmon', 'skyblue'],
             histtype='bar',
             alpha=0.95)

    plt.axvline(x=x_value, color='black', linestyle='--', label=f'diagonal slope of 1/{lookback}')
    plt.axvline(x=-x_value, color='black', linestyle='--')  # If you want a line symmetric on the negative side

    plt.xlabel('Slope')
    plt.ylabel('Count')
    plt.yscale('log')
    plt.title(f'Histogram of {error_type} by Slope ({lookback}-day Model)')
    plt.grid(axis='y', linestyle='--', alpha=0.7)

    # Plot ratio as line with a second y-axis
    ax1 = plt.gca()
    ax2 = ax1.twinx()
    bin_centers = (bin_edges[:-1] + bin_edges[1:]) / 2
    ax2.plot(bin_centers, ratio, color='black', marker='o', label=f'{error_type}/Total Ratio')
    ax2.set_ylabel(f'{error_type}/Total Ratio')
    ax2.set_ylim(0, 1)

    ax1.legend(loc='upper left')    # bar chart legend
    ax2.legend(loc='upper right')   # ratio line legend
    
    plt.tight_layout()
    plt.savefig(wdir / f"{error_type}_histogram_{lookback}_slopes.png", dpi=300)
    plt.close()

