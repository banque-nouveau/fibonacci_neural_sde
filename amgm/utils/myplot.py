def plot_fib_levels(fib_levels, ax):
    """ 
    Plots Fibonacci levels on the given axis with labels and colors. 
    """
    fib_names = ["0.0","0.23", "0.38", "0.5", "0.61", "0.78","1.0"]  # adjust to your levels
    colors = plt.cm.tab10.colors
    for i, level in enumerate(fib_levels):
        color = colors[i % len(colors)]
        name = fib_names[i] if i < len(fib_names) else f"fib_{i}"

        ax.axhline(y=level, color=color, linestyle="--", linewidth=1.5)
        ax.text(
            1.01, level, name,
            transform=ax.get_yaxis_transform(),
            color=color,
            va="center",
            ha="left",
            fontsize=9,
            bbox=dict(facecolor="white", alpha=0.75, edgecolor="none", pad=1.5),
        )
            
def regression_residual_performance(y_true, y_hat, wdir, 
                                    bin_names=None, mean_MAE=None, std_MAE=None, 
                                    dataset_type=None, 
                                    model="daily_378_63_US_Stocks", 
                                    output_range=50):
    """
    Plots the regression residual performance with two subplots:
    1. Mean Absolute Error (MAE) per bin
    2. Scatter plot of predictions vs true labels with mean and std error bars for each bin.
    
    Parameters:
    y_true (np.ndarray): True labels.
    y_hat (np.ndarray): Predicted labels.
    wdir (Path): Directory to save the plots.
    bin_names (list of str): ['gt20', '15to20', '10to15', '5to10', '0to5', 'zero', 'n0to4', 'n4to8', 'n8to12', 'n12to15', 'lt15']
    mean_MAE (array-like): Mean MAE for each bin.
    std_MAE (array-like): Standard deviation of MAE for each bin.
    dataset_type (str): Type of dataset, either "train" or "validation".
    model (str): Model identifier, e.g., "daily_378_63".
    output_range (int): Range of output values for the max residual.
    """

    fig, axes = plt.subplots(1, 2, figsize=(16, 6))
    # Set a common title for the entire figure
    fig.suptitle("Regression Residual Performance, labels: max residual percentages during lookforward period", fontsize=16, fontweight='bold')
    # Subplot 1: MAE per bin
    axes[0].errorbar(bin_names, mean_MAE, yerr=std_MAE, fmt='-o', ecolor='r', capsize=5, label='MAE ± Std')
    axes[0].set_xlabel('Max Residual Bin (%)')
    axes[0].set_ylabel('Mean Absolute Error (%)')
    axes[0].set_title("Average MAE of maximum residual percentages vs Bins")
    axes[0].legend()
    axes[0].grid(True)
    
    # Subplot 2: prediction vs label scatter
    axes[1].scatter(y_true, y_hat, alpha=0.2, s=5, label='Predictions')
    axes[1].plot([-output_range, output_range], [-output_range, output_range], 'r--', label='Ideal: y_hat = y_true')
    axes[1].set_xlabel('Label')
    axes[1].set_ylabel('Prediction')
    axes[1].set_title("Predictions vs True Labels")
    axes[1].legend()
    axes[1].grid(True)
    
    plt.tight_layout()
    if wdir is not None:
        file_name = f"regression_residual_{model}_{dataset_type}.png" if dataset_type is not None else f"regression_residual_{model}.png"
        plt.savefig(wdir / file_name)
        plt.close()
    else:
        return fig


